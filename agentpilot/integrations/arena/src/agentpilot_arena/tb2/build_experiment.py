def _root_seed_tables(
    baseline: RootBaseline | None,
    *,
    root_commit_sha: str,
    apparatus_digest: str,
    total_tasks: int,
) -> str:
    if baseline is None:
        result_lines = note_lines = excerpt_lines = exclusion_lines = ""
        primary_value = 0.0
        measured = "false"
        aggregate = ""
    else:
        result_lines = "\n".join(
            f"{_quote(f'visible-a/{task_id}/0')} = {str(result).lower()}"
            for task_id, result in sorted(baseline.task_results.items())
        )
        note_lines = "\n".join(
            f"{_quote(f'visible-a/{task_id}/0')} = {_quote(note)}"
            for task_id, note in sorted(baseline.task_notes.items())
        )
        excerpt_lines = "\n".join(
            f"{_quote(f'visible-a/{task_id}/0')} = {_quote(excerpt)}"
            for task_id, excerpt in sorted(baseline.task_excerpts.items())
        )
        exclusion_lines = "\n".join(
            f"{_quote(f'visible-a/{task_id}/0')} = {_quote(reason)}"
            for task_id, reason in sorted(baseline.task_exclusions.items())
        )
        primary_value = baseline.primary_value
        measured = "true"
        n_conclusive = len(baseline.task_results)
        n_excluded = len(baseline.task_exclusions)
        n_passed = sum(baseline.task_results.values())
        aggregate = f"""\n[environment.settings.root_seed.aggregate]
n_total = {total_tasks}
n_attempted = {total_tasks}
n_conclusive = {n_conclusive}
n_excluded = {n_excluded}
n_inconclusive = {n_excluded}
n_passed = {n_passed}
pass_rate = {primary_value!r}
"""
    return f"""[environment.settings.root_seed]
parent_id = "tb2-root"
commit_sha = {_quote(root_commit_sha)}
apparatus_digest = {_quote(apparatus_digest)}
available_at = "1970-01-01T00:00:00Z"
measured = {measured}
primary_value = {primary_value!r}

[environment.settings.root_seed.cell_results]
{result_lines}

[environment.settings.root_seed.cell_notes]
{note_lines}

[environment.settings.root_seed.cell_excerpts]
{excerpt_lines}
\n[environment.settings.root_seed.cell_exclusions]
{exclusion_lines}
{aggregate}
"""


